const uint32_t* translate_keycode_only_shift(uint8_t used_lang, uint16_t keycode) {
    uint16_t index = keycode - KC_A;

    if(keycode==KC_NONUS_BACKSLASH) {
        index = ALPHA + NUM + ADDITIONAL - 1;
    } else if((keycode < KC_A || keycode > KC_SLASH)) {
        return NULL;
    }
    return  lang_plane[index][used_lang*4 + VAR_SHIFT];
}

const uint32_t* translate_keycode_only_altgr(uint8_t used_lang, uint16_t keycode) {
    uint16_t index = keycode - KC_A;

    if(keycode==KC_NONUS_BACKSLASH) {
        index = ALPHA + NUM + ADDITIONAL - 1;
    } else if((keycode < KC_A || keycode > KC_SLASH)) {
        return NULL;
    }
    return  lang_plane[index][used_lang*4 + VAR_ALTGR];
}

const uint32_t* translate_keycode(uint8_t used_lang, uint16_t keycode, bool shift, bool caps_lock) {
    uint16_t index = keycode - KC_A;

    if(keycode==KC_NONUS_BACKSLASH) {
        index = ALPHA + NUM + ADDITIONAL - 1;
    } else if((keycode < KC_A || keycode > KC_SLASH)) {
        return NULL;
    }

    const uint32_t* lower_case = lang_plane[index][used_lang*4 + VAR_SMALL];
    if(lower_case==NULL) {
        lower_case = lang_plane[index][0]; //english as backup
        used_lang = 0;
    }

    if(caps_lock) {
        const uint32_t* caps_case = lang_plane[index][used_lang*4 + VAR_CAPS];
        if(caps_case!=NULL) {
            if(!shift) {
                return caps_case;
            }
        } else {
            shift = !shift;
        }
    }

    if(shift) {
        const uint32_t* upper_case = lang_plane[index][used_lang*4 + VAR_SHIFT];
        if(upper_case!=NULL) {
            return upper_case;
        }
    }
    return lower_case;
}


