#!/usr/bin/env python3
"""Draw the MIDI keycap symbols and write them into the resident IconsFont.

    python3 tools/midi_glyphs.py            # from keyboards/polykybd/: rewrite both blocks
    python3 tools/midi_glyphs.py --check    # exit 1 if a header is out of date
    python3 tools/midi_glyphs.py --sheet out.png   # every glyph on a 72x40 keycap

Every glyph is drawn on the 72x40 keycap in PANEL coordinates and stored with that
position in its metrics: xOffset = left column, yOffset = top row - 23 (the static
legend baseline), xAdvance = 0. A legend therefore draws the symbol FIRST, at the
legend origin, and the text after it starts where it would have anyway. The text
boxes and the symbol boxes are kept at least 4 px apart, because the firmware
clears a 3 px courtyard around every glyph box before plotting it
(kdisp_write_gfx_char); midi_legend.c's layout and this file must agree on that.

Sources:
  * staff, hairpins, slur, glide, vibrato wave, bend curves: drawn here.
  * dynamics (U+1D18F..1D191), flat, sharp, treble clef (U+1D11E) and the text marks
    (8va, 8vb, Ped., Sost., u.c.): GNU FreeFont FreeSerif / FreeSerifBoldItalic
    (GPLv3 with the font exception; Debian package fonts-freefont-ttf). Only the
    rendered 1-bit bitmaps are stored, below.

The glyphs are appended to IconsFont between the BEGIN/END markers, so the font's
`last` moves and nothing else does: no pack index shifts and no bundle is reshipped
(FONT_PACK.md). The macros go to lang/named_glyphs.h, outside the cog block, which
is what tools/check_icon_slots.py cross-checks.
"""
import argparse
import math
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
KB = os.path.dirname(HERE)
ICONS_H = os.path.join(KB, "base", "fonts", "gfx_icons.h")
NAMES_H = os.path.join(KB, "lang", "named_glyphs.h")
FREESERIF = "/usr/share/fonts/truetype/freefont/FreeSerif.ttf"
FREESERIF_BI = "/usr/share/fonts/truetype/freefont/FreeSerifBoldItalic.ttf"

W, H = 72, 40
BASELINE = 23
# The MIDI block starts right after IconsFont's last glyph that is not ours, read from
# the header each run, so another feature appending its own icon first moves the block
# instead of colliding with it (ICON_AI_KEY took U+100029 while this PR was open).

BEGIN_BMP = "  /* ---- BEGIN MIDI glyphs: generated by tools/midi_glyphs.py, do not edit ---- */"
END_BMP = "  /* ---- END MIDI glyphs (bitmaps) ---- */"
BEGIN_GLY = "  /* ---- BEGIN MIDI glyphs (metrics) ---- */"
END_GLY = "  /* ---- END MIDI glyphs (metrics) ---- */"
BEGIN_MAC = "// ---- BEGIN MIDI glyphs: generated by tools/midi_glyphs.py, do not edit ----"
END_MAC = "// ---- END MIDI glyphs ----"


# ---- drawing helpers (canvas = one 72x40 keycap) --------------------------------
def canvas():
    return Image.new("1", (W, H), 0)


def font_glyph(text, size, path=FREESERIF, thresh=110):
    f = ImageFont.truetype(path, size)
    im = Image.new("L", (240, 160), 0)
    ImageDraw.Draw(im).text((40, 40), text, font=f, fill=255)
    bb = im.getbbox()
    return im.crop(bb).point(lambda v: 255 if v > thresh else 0).convert("1")


def paste(c, g, x, y):
    c.paste(1, (x, y), g)


def centred(c, g, cx=36, cy=20):
    paste(c, g, cx - g.width // 2, cy - g.height // 2)


def plot(c, pts):
    px = c.load()
    for x, y in pts:
        if 0 <= x < W and 0 <= y < H:
            px[x, y] = 1


HEAD = ["..###..", ".#####.", "#######", ".#####.", "..###.."]  # centre row 2
SHARP = [".#.#.", ".#.#.", "#####", ".#.#.", "#####", ".#.#.", ".#.#."]  # centre row 3


def pattern(c, rows, x, y):
    plot(c, [(x + dx, y + dy) for dy, r in enumerate(rows) for dx, ch in enumerate(r) if ch == "#"])


# ---- the staff: one glyph per pitch class -----------------------------------------
STAFF_X0, STAFF_X1 = 42, 71
STAFF_LINES = (8, 13, 18, 23, 28)  # F5 at the top, E4 at the bottom
STEP = {"C": -2, "D": -1, "E": 0, "F": 1, "G": 2, "A": 3, "B": 4}  # diatonic steps above E4
HEAD_X = 61
NOTE_NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]


def staff(name):
    c = canvas()
    plot(c, [(x, y) for y in STAFF_LINES for x in range(STAFF_X0, STAFF_X1 + 1)])
    step = STEP[name[0]]
    yc = 28 - (5 * step) // 2 if step % 2 == 0 else 28 - (5 * step + 1) // 2
    pattern(c, HEAD, HEAD_X, yc - 2)
    if step <= -2:  # middle C sits on a ledger line
        plot(c, [(x, 33) for x in range(HEAD_X - 2, HEAD_X + 9)])
    if step < 4:  # stem up below the middle line
        plot(c, [(HEAD_X + 6, y) for y in range(yc - 14, yc)])
    else:
        plot(c, [(HEAD_X, y) for y in range(yc + 1, yc + 15)])
    if name.endswith("#"):
        pattern(c, SHARP, HEAD_X - 7, yc - 3)
    return c


# ---- the other symbols ---------------------------------------------------------------
def dynamic(marks, size=34):
    c = canvas()
    cps = {"p": "\U0001D18F", "m": "\U0001D190", "f": "\U0001D191"}
    centred(c, font_glyph("".join(cps[m] for m in marks), size))
    return c


def hairpin(cresc):  # right of a VEL label/value, x 40..69
    c = canvas()
    x0, x1, yc, h = 40, 69, 27, 7
    pts = []
    for x in range(x0, x1 + 1):
        t = (x - x0) / (x1 - x0)
        dy = round(h * (t if cresc else 1 - t))
        pts += [(x, yc - dy), (x, yc + dy)]
    plot(c, pts)
    return c


def accidental(ch):  # right of a TRNS label, x 56..
    c = canvas()
    paste(c, font_glyph(ch, 30), 56, 6)
    return c


def octave_mark(text):  # under the OCT label, right of the value
    c = canvas()
    paste(c, font_glyph(text, 20, FREESERIF_BI), 36, 19)
    return c


def word_mark(text, size):
    c = canvas()
    centred(c, font_glyph(text, size, FREESERIF_BI), cy=19)
    return c


def legato():  # stems down, slur above, right of "LEG"
    c = canvas()
    pattern(c, HEAD, 40, 14)
    plot(c, [(40, y) for y in range(16, 35)])
    pattern(c, HEAD, 58, 10)
    plot(c, [(58, y) for y in range(12, 31)])
    x0, x1, ytop, h = 39, 65, 8, 3
    pts = []
    for x in range(x0, x1 + 1):
        t = (x - x0) / (x1 - x0)
        y = round(ytop - 4 * h * t * (1 - t))
        pts += [(x, y), (x, y + 1)]
    plot(c, pts)
    return c


def portamento():  # two heads joined by a glide, under "PORT"
    c = canvas()
    pattern(c, HEAD, 34, 31)
    pattern(c, HEAD, 62, 20)
    x0, y0, x1, y1 = 41, 33, 61, 22
    pts = []
    for x in range(x0, x1 + 1):
        y = round(y0 + (y1 - y0) * (x - x0) / (x1 - x0))
        pts += [(x, y), (x, y + 1)]
    plot(c, pts)
    return c


def wave():  # vibrato under "MOD"
    c = canvas()
    pts = []
    for x in range(8, 67):
        y = round(30 + 4 * math.sin(2 * math.pi * (x - 8) / 12))
        pts += [(x, y), (x, y + 1)]
    plot(c, pts)
    return c


def bend(up):  # under "BEND", y 22..36
    c = canvas()
    pts = []
    for x in range(10, 65):
        t = (x - 10) / 54
        y = round(36 - 14 * t * t) if up else round(22 + 14 * t * t)
        pts += [(x, y), (x, y + 1)]
    plot(c, pts)
    return c


def clef():  # the MIDI layer key, left column
    c = canvas()
    paste(c, font_glyph("\U0001D11E", 33), 4, 2)
    return c


GLYPHS = ([(f"ICON_MIDI_STAFF_{n.replace('#', 'S')}", staff(n), f"staff, {n}") for n in NOTE_NAMES] + [
    ("ICON_MIDI_PP", dynamic("pp"), "dynamic pp"),
    ("ICON_MIDI_P", dynamic("p"), "dynamic p"),
    ("ICON_MIDI_MP", dynamic("mp"), "dynamic mp"),
    ("ICON_MIDI_MF", dynamic("mf"), "dynamic mf"),
    ("ICON_MIDI_F", dynamic("f"), "dynamic f"),
    ("ICON_MIDI_FF", dynamic("ff"), "dynamic ff"),
    ("ICON_MIDI_CRESC", hairpin(True), "crescendo hairpin, velocity up"),
    ("ICON_MIDI_DIM", hairpin(False), "diminuendo hairpin, velocity down"),
    ("ICON_MIDI_FLAT", accidental("\u266D"), "flat, transpose down"),
    ("ICON_MIDI_SHARP", accidental("\u266F"), "sharp, transpose up"),
    ("ICON_MIDI_8VA", octave_mark("8va"), "ottava alta, octave up"),
    ("ICON_MIDI_8VB", octave_mark("8vb"), "ottava bassa, octave down"),
    ("ICON_MIDI_PED", word_mark("Ped.", 22), "sustain pedal mark"),
    ("ICON_MIDI_SOST", word_mark("Sost.", 22), "sostenuto pedal mark"),
    ("ICON_MIDI_UC", word_mark("u.c.", 24), "una corda, soft pedal"),
    ("ICON_MIDI_LEGATO", legato(), "two notes under a slur"),
    ("ICON_MIDI_PORTA", portamento(), "two notes joined by a glide"),
    ("ICON_MIDI_WAVE", wave(), "vibrato wave, modulation"),
    ("ICON_MIDI_BEND_UP", bend(True), "pitch bend up"),
    ("ICON_MIDI_BEND_DOWN", bend(False), "pitch bend down"),
    ("ICON_MIDI_CLEF", clef(), "treble clef, the MIDI layer key"),
])


# ---- encoding ------------------------------------------------------------------------
def crop(c):
    bb = c.getbbox()
    if bb is None:
        raise ValueError("empty glyph")
    return c.crop(bb), bb[0], bb[1]


def glyph_bytes(im):
    """Column-native bitmap: per column, (h+7)//8 bytes, bit (y & 7) of byte y >> 3.
    The same layout as tools/hint_icons.py and every other IconsFont glyph."""
    w, h = im.size
    px = im.load()
    cb = (h + 7) >> 3
    out = []
    for x in range(w):
        col = [0] * cb
        for y in range(h):
            if px[x, y]:
                col[y >> 3] |= 1 << (y & 7)
        out += col
    return out


def art(im):
    px = im.load()
    return ["".join("#" if px[x, y] else "." for x in range(im.width)) for y in range(im.height)]


def build(bitmap_start, first_cp):
    bmp_lines, gly_lines, mac_lines = [], [], []
    off = bitmap_start
    for i, (name, c, what) in enumerate(GLYPHS):
        cp = first_cp + i
        im, left, top = crop(c)
        data = glyph_bytes(im)
        bmp_lines.append(f"  /* 0x{cp:06X} {name} {im.width}x{im.height}: {what}.")
        bmp_lines += [f"     {row}" for row in art(im)]
        bmp_lines.append("  */")
        for k in range(0, len(data), 16):
            bmp_lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[k:k + 16]) + ",")
        gly_lines.append(f"  {{ {off:5d}, {im.width:3d}, {im.height:3d}, {0:3d}, {left:4d}, {top - BASELINE:4d} }},"
                         f"   // 0x{cp:06X} {name}")
        mac_lines.append(f'#define {name:<28}U"\\x{cp:06X}"')
        off += len(data)
    return bmp_lines, gly_lines, mac_lines, first_cp + len(GLYPHS) - 1


def strip_block(text, begin, end):
    if begin in text:
        a = text.index(begin)
        b = text.index(end, a) + len(end) + 1
        return text[:a] + text[b:]
    return text


def bitmap_len(body):
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    return len(re.findall(r"0x[0-9A-Fa-f]{2}\b", body))


def render_icons(src):
    src = strip_block(src, BEGIN_BMP, END_BMP)
    src = strip_block(src, BEGIN_GLY, END_GLY)
    m = re.search(r"(const uint8_t IconsBitmaps\[\] PROGMEM = \{)(.*?)(\n\};)", src, re.S)
    start = bitmap_len(m.group(2))
    # The font's `last` already counts our block on a re-run, so count the glyph records
    # left after stripping it instead: the table is contiguous from `first`.
    first = int(re.search(r"\(GFXglyph \*\)IconsGlyphs, (0x[0-9A-Fa-f]+),", src).group(1), 16)
    table = re.search(r"const GFXglyph IconsGlyphs\[\] PROGMEM = \{(.*?)\n\};", src, re.S).group(1)
    base_last = first + len(re.findall(r"^\s*\{", table, re.M)) - 1
    bmp, gly, mac, last = build(start, base_last + 1)
    src = src[:m.end(2)] + "\n" + BEGIN_BMP + "\n" + "\n".join(bmp) + "\n" + END_BMP + src[m.end(2):]
    g = re.search(r"(const GFXglyph IconsGlyphs\[\] PROGMEM = \{)(.*?)(\n\};)", src, re.S)
    src = src[:g.end(2)] + "\n" + BEGIN_GLY + "\n" + "\n".join(gly) + "\n" + END_GLY + src[g.end(2):]
    src = re.sub(r"(\(GFXglyph \*\)IconsGlyphs, 0x[0-9A-Fa-f]+, )0x[0-9A-Fa-f]+", lambda mm: mm.group(1) + f"0x{last:06X}", src, count=1)
    return src, mac, base_last


def render_names(src, mac, after_cp):
    src = strip_block(src, BEGIN_MAC, END_MAC)
    # After the macro of the font's last glyph that is not ours, so the macros stay in
    # codepoint order.
    anchor = re.search(r'#define ICON_\w+\s+U"\\x%06X"\n' % after_cp, src)
    if anchor is None:
        raise SystemExit(f"named_glyphs.h has no macro for U+{after_cp:06X}")
    block = (BEGIN_MAC + "\n// MIDI layer symbols (midi_legend.c). Each is drawn at its own position on the\n"
             "// keycap with xAdvance 0, so a legend puts it FIRST and its text after it.\n" + "\n".join(mac) + "\n" + END_MAC + "\n")
    return src[:anchor.end()] + block + src[anchor.end():]


def sheet(path, scale=4):
    cols = 6
    rows = (len(GLYPHS) + cols - 1) // cols
    out = Image.new("RGB", (cols * (W * scale + 8) + 8, rows * (H * scale + 8) + 8), (30, 30, 30))
    for i, (_, c, _) in enumerate(GLYPHS):
        rgb = Image.new("RGB", (W, H), (8, 8, 12))
        rgb.paste((235, 235, 255), (0, 0), c)
        out.paste(rgb.resize((W * scale, H * scale), Image.NEAREST), (8 + (i % cols) * (W * scale + 8), 8 + (i // cols) * (H * scale + 8)))
    out.save(path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--sheet")
    a = ap.parse_args()
    if a.sheet:
        sheet(a.sheet)
        print("wrote", a.sheet)
        return 0
    icons = open(ICONS_H, encoding="utf-8").read()
    names = open(NAMES_H, encoding="utf-8").read()
    new_icons, mac, base_last = render_icons(icons)
    new_names = render_names(names, mac, base_last)
    if a.check:
        stale = [p for p, old, new in ((ICONS_H, icons, new_icons), (NAMES_H, names, new_names)) if old != new]
        for p in stale:
            print("out of date:", os.path.relpath(p, KB))
        return 1 if stale else 0
    open(ICONS_H, "w", encoding="utf-8").write(new_icons)
    open(NAMES_H, "w", encoding="utf-8").write(new_names)
    print(f"wrote {len(GLYPHS)} glyphs, U+{base_last + 1:06X}..U+{base_last + len(GLYPHS):06X}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
